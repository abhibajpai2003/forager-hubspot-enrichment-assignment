"""A fake Forager API for FORAGER_MODE=mock.

It answers every endpoint the service uses with clearly fake, deterministic data shaped like
Forager's real responses, so the whole flow (webhooks, HubSpot writes, title filtering) can be
exercised end to end without spending credits. In title searches every fourth person has no
work email, to exercise the "try the next candidate" path.
"""

import hashlib
import json
import re
import uuid
from typing import Any

import httpx

FIRST_NAMES = ["Avery", "Jordan", "Riley", "Morgan", "Casey", "Quinn", "Taylor", "Drew"]
LAST_NAMES = ["Mockford", "Sampleton", "Testwell", "Demoray", "Stubbs", "Fixtureson"]
LOCATIONS = [
    ("San Francisco", "California", "United States"),
    ("New York", "New York", "United States"),
    ("London", "England", "United Kingdom"),
]


def _n(*parts: Any) -> int:
    digest = hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()
    return int(digest[:8], 16)


def _org(domain: str) -> dict[str, Any]:
    stem = domain.split(".")[0]
    name = f"{stem.capitalize()} (mock)"
    return {
        "id": _n("org", domain) % 1_000_000,
        "name": name,
        "legal_name": f"{stem.capitalize()} Mock Inc.",
        "website": f"https://{domain}",
        "domain": domain,
        "description": f"[MOCK DATA] {name} builds things. Generated by the Forager mock.",
        "founded_date": "2015-12-11",
        "employees_range": "1001-5000",
        "employees_amount": 3500,
        "keywords": [{"id": 1, "name": "mock"}, {"id": 2, "name": "testing"}],
        "location": _location(0),
        "finance_info": {"revenue": 1_000_000_000},
        "linkedin_info": {
            "public_identifier": f"{stem}-mock",
            "public_profile_url": f"https://www.linkedin.com/company/{stem}-mock",
            "industry": {"id": 4, "name": "Software Development"},
        },
        "addresses": [
            {
                "street_number": "1",
                "street_name": "Mock Street",
                "city": "San Francisco",
                "state": "California",
                "postcode": "94110",
                "country": "United States",
                "summary": "1 Mock Street, San Francisco, California 94110, United States",
            }
        ],
    }


def _location(i: int) -> dict[str, Any]:
    city, state, country = LOCATIONS[i % len(LOCATIONS)]
    return {
        "id": i + 1,
        "name": f"{city}, {state}, {country}",
        "osm_locations": [
            {"id": 10 * i + 1, "name": city, "place_type": "city"},
            {"id": 10 * i + 2, "name": state, "place_type": "state"},
            {"id": 10 * i + 3, "name": country, "place_type": "country"},
        ],
    }


def _person(index: int, *, first: str | None = None, last: str | None = None) -> dict[str, Any]:
    first = first or FIRST_NAMES[index % len(FIRST_NAMES)]
    last = last or LAST_NAMES[index % len(LAST_NAMES)]
    slug = f"{first}-{last}-mock{index}".lower()
    return {
        "id": 500_000 + index,
        "full_name": f"{first} {last}",
        "first_name": first,
        "last_name": last,
        "headline": f"[MOCK DATA] Person #{index}",
        "description": "[MOCK DATA] About section text from the Forager mock.",
        "skills": [{"name": "Testing"}, {"name": "Mocking"}],
        "location": _location(index),
        "linkedin_info": {
            "public_identifier": slug,
            "public_profile_url": f"https://www.linkedin.com/in/{slug}",
            "industry": {"id": 4, "name": "Software Development"},
        },
    }


def _role(index: int, title: str, org: dict[str, Any], person: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": 900_000 + index,
        "role_title": title,
        "start_date": "2023-01-01",
        "is_current": True,
        "organization": org,
        "person": person,
    }


def _email_for(slug: str, domain: str) -> str:
    local = ".".join(p for p in slug.split("-")[:2] if p)
    return f"{local}@{domain}"


class _MockForager:
    def __init__(self) -> None:
        self.jobs: dict[str, dict[str, Any]] = {}
        self.slug_domains: dict[str, str] = {}
        self.org_domains: dict[int, str] = {}
        self.no_email: set[str] = set()
        self.default_domain = "example.com"

    def handle(self, request: httpx.Request) -> httpx.Response:
        path = request.url.path
        body: dict[str, Any] = json.loads(request.content) if request.content else {}

        if path == "/api/users/current/":
            return httpx.Response(200, json={"accounts": []})
        if path.endswith("/organization_search/"):
            domains = body.get("domains") or [self.default_domain]
            org = _org(domains[0])
            self.org_domains[org["id"]] = domains[0]
            return httpx.Response(200, json={"search_results": [org], "total_search_results": 1})
        if path.endswith("/person_role_search/totals/"):
            results = self._role_search(body)
            return httpx.Response(
                200,
                json={
                    "total_search_results": len(results),
                    "total_persons": len(results),
                    "total_organizations": 1,
                },
            )
        if path.endswith("/person_role_search/"):
            results = self._role_search(body)
            return httpx.Response(
                200, json={"search_results": results, "total_search_results": len(results)}
            )
        if path.endswith("/by_email/"):
            return self._reverse_email(str(body.get("email", "")))
        if path.endswith("/phone_numbers/"):
            return httpx.Response(200, json=[{"phone_number": "+14155550100"}])
        if "/work_emails/" in path and request.method == "POST":
            job_id = str(uuid.uuid5(uuid.NAMESPACE_URL, json.dumps(body, sort_keys=True)))
            self.jobs[job_id] = body
            return httpx.Response(
                202,
                json={
                    "job_id": job_id,
                    "status": "queued",
                    "status_check_url": f"{path}{job_id}/",
                    "webhook_url": "",
                },
            )
        if "/work_emails/" in path and request.method == "GET":
            return self._email_job(path.rstrip("/").rsplit("/", 1)[-1])
        return httpx.Response(404, json={"detail": "Not found."})

    def _role_search(self, body: dict[str, Any]) -> list[dict[str, Any]]:
        org_ids = body.get("organizations") or []
        domains = body.get("organization_domains") or [
            self.org_domains.get(org_ids[0], self.default_domain)
            if org_ids
            else self.default_domain
        ]
        org = _org(domains[0])
        if body.get("person_linkedin_public_identifiers"):
            slug = body["person_linkedin_public_identifiers"][0]
            person = _person(_n(slug) % 50)
            person["linkedin_info"]["public_identifier"] = slug
            person["linkedin_info"]["public_profile_url"] = f"https://www.linkedin.com/in/{slug}"
            self.slug_domains[slug] = domains[0]
            return [_role(_n(slug) % 50, "Mock Engineer", org, person)]
        if body.get("person_name"):
            name = str(body["person_name"]).replace('"', "").split()
            first, last = [*name, "Mock"][:2]
            index = _n(first, last) % 50
            person = _person(index, first=first, last=last)
            self.slug_domains[person["linkedin_info"]["public_identifier"]] = domains[0]
            return [_role(index, "Mock Engineer", org, person)]
        if int(body.get("page") or 1) > 1:
            return []
        titles = re.findall(r'"([^"]+)"', str(body.get("role_title") or "")) or ["Mock Role"]
        results = []
        for t_index, title in enumerate(titles):
            for k in range(2):
                index = t_index * 2 + k
                person = _person(index)
                slug = person["linkedin_info"]["public_identifier"]
                self.slug_domains[slug] = domains[0]
                if index % 4 == 3:
                    self.no_email.add(slug)
                results.append(_role(index, title, org, person))
        return results

    def _reverse_email(self, email: str) -> httpx.Response:
        if "@" not in email:
            return httpx.Response(404, json={"detail": "Not found."})
        local, domain = email.split("@", 1)
        names = re.split(r"[._-]", local)
        first = names[0].capitalize()
        last = names[1].capitalize() if len(names) > 1 else "Mock"
        index = _n(first, last) % 50
        person = _person(index, first=first, last=last)
        org = _org(domain)
        person["roles"] = [
            {
                "id": 1,
                "role_title": "Mock Engineer",
                "start_date": "2022-05-01",
                "is_current": True,
                "organization": {
                    "id": org["id"],
                    "name": org["name"],
                    "domain": domain,
                    "linkedin_info": org["linkedin_info"],
                },
            }
        ]
        return httpx.Response(200, json=person)

    def _email_job(self, job_id: str) -> httpx.Response:
        body = self.jobs.get(job_id)
        if body is None:
            return httpx.Response(404, json={"detail": "Not found."})
        slug = body.get("linkedin_public_identifier") or (
            f"{body.get('first_name', '')}-{body.get('last_name', '')}-mock0".lower()
        )
        domain = body.get("domain") or self.slug_domains.get(slug) or self.default_domain
        email = None if slug in self.no_email else _email_for(slug, domain)
        return httpx.Response(
            200,
            json={
                "job_id": job_id,
                "status": "completed",
                "result": "found" if email else "not_found",
                "emails": [email] if email else [],
                "error_code": None,
                "person_id": None,
                "submitted_lookup": body,
            },
        )


def mock_transport(default_domain: str = "example.com") -> httpx.MockTransport:
    mock = _MockForager()
    mock.default_domain = default_domain
    return httpx.MockTransport(mock.handle)
